# ---------------------------------------------------------------------------
# One-time setup for dsh-connect-deveco on Windows.
#
# Run in PowerShell from anywhere:
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\setup-windows.ps1
#
# It performs three independent setup steps (safe to re-run):
#   1. Installs the vendored proxy's runtime dependency (undici) locally.
#   2. Sets the DEVECO_DUMMY_KEY user environment variable (a non-empty
#      placeholder the DSH provider needs; the local proxy ignores its value).
#   3. Installs a per-user Startup shortcut that silently launches the proxy at
#      logon (no administrator rights required).
#
# It does NOT register the DSH provider — do that by merging config/dsh-provider.yml
# into your profile (see README). It does NOT touch any Huawei credentials.
# ---------------------------------------------------------------------------

$ErrorActionPreference = "Stop"
$PluginDir = Split-Path -Parent $PSScriptRoot
$ProxyDir  = Join-Path $PluginDir "vendor\opencode-deveco"

Write-Host "== dsh-connect-deveco setup =="

# 1. Runtime dependency for the vendored proxy (dist/env-fetch.js imports undici).
#    The vendored copy already ships undici, but re-running npm install keeps it
#    reproducible if the user replaced the vendor dir with their own checkout.
if (Test-Path (Join-Path $ProxyDir "node_modules\undici")) {
  Write-Host "[1/3] undici already present in vendor runtime. Skip."
} else {
  Write-Host "[1/3] Installing vendored proxy dependencies (npm install)..."
  Push-Location $ProxyDir
  try { npm install --omit=dev --no-audit --no-fund } finally { Pop-Location }
}

# 2. Placeholder API key for the DSH provider (user scope, no admin needed).
if ([Environment]::GetEnvironmentVariable("DEVECO_DUMMY_KEY", "User")) {
  Write-Host "[2/3] DEVECO_DUMMY_KEY already set. Skip."
} else {
  [Environment]::SetEnvironmentVariable("DEVECO_DUMMY_KEY", "dsh-local-proxy-placeholder", "User")
  Write-Host "[2/3] Set DEVECO_DUMMY_KEY (restart DSH to inherit it)."
}

# 3. Silent logon autostart via the Startup folder (VBS → hidden PowerShell).
$Startup = [Environment]::GetFolderPath("Startup")
$Vbs = Join-Path $Startup "DevEcoProxy.vbs"
$StartPs1 = Join-Path $ProxyDir "scripts\start-windows.ps1"
if (Test-Path $Vbs) {
  Write-Host "[3/3] Startup launcher already installed. Skip."
} else {
  $vbsBody = @"
' Auto-generated by dsh-connect-deveco setup. Launches the proxy hidden at logon.
On Error Resume Next
Set ws = CreateObject("WScript.Shell")
ws.CurrentDirectory = "$ProxyDir"
ws.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -File ""$StartPs1""", 0, False
"@
  Set-Content -Path $Vbs -Value $vbsBody -Encoding ASCII
  Write-Host "[3/3] Installed logon launcher: $Vbs"
}

Write-Host ""
Write-Host "Setup complete. Next steps:"
Write-Host "  1) Merge config\dsh-provider.yml into your DSH profile's llm-pi-ai providers."
Write-Host "  2) Restart DSH, install/enable this bundle plugin, and refresh the Web GUI (F5)."
Write-Host "  3) In Settings -> DevEco Code, click Login and authorize in the browser."
